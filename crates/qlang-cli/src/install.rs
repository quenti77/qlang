//! `qlang install | update | add | remove`: fetching the git packages a project depends
//! on into `.qlang/packages/<name>`, at the exact commits recorded in `qlang.lock`.
//!
//! Git is run as the `git` program. Only these transports are allowed (so that a
//! `qlang.toml` cannot make git run a command through `ext::`): https, ssh, git, file.

use crate::packages::{GitRef, Source, manifest_of, packages_dir, parse_dependencies};
use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

const LOCK_FILE: &str = "qlang.lock";

/// One locked git package.
#[derive(Clone, Debug, PartialEq, Eq)]
struct Locked {
    git: String,
    spec: String,
    commit: String,
}

fn read_lock(project: &Path) -> Result<HashMap<String, Locked>, String> {
    let file = project.join(LOCK_FILE);
    if !file.is_file() {
        return Ok(HashMap::new());
    }
    let text = std::fs::read_to_string(&file)
        .map_err(|e| format!("cannot read {}: {e}", file.display()))?;
    let table: toml::Table = text
        .parse()
        .map_err(|e| format!("{}: {e}", file.display()))?;
    let mut out = HashMap::new();
    for entry in table
        .get("package")
        .and_then(|p| p.as_array())
        .map(Vec::as_slice)
        .unwrap_or(&[])
    {
        let field = |k: &str| entry.get(k).and_then(|v| v.as_str()).map(str::to_string);
        if let (Some(name), Some(git), Some(spec), Some(commit)) =
            (field("name"), field("git"), field("ref"), field("commit"))
        {
            out.insert(name, Locked { git, spec, commit });
        }
    }
    Ok(out)
}

fn write_lock(project: &Path, lock: &BTreeMap<String, Locked>) -> Result<(), String> {
    let file = project.join(LOCK_FILE);
    if lock.is_empty() {
        let _ = std::fs::remove_file(&file);
        return Ok(());
    }
    let mut text = String::from("# generated by `qlang install`; commit it, do not edit it\n");
    for (name, l) in lock {
        text.push_str(&format!(
            "\n[[package]]\nname = {name:?}\ngit = {:?}\nref = {:?}\ncommit = {:?}\n",
            l.git, l.spec, l.commit
        ));
    }
    if std::fs::read_to_string(&file).ok().as_deref() == Some(text.as_str()) {
        return Ok(());
    }
    std::fs::write(&file, text).map_err(|e| format!("cannot write {}: {e}", file.display()))
}

/// Removes a directory tree, including the read-only files git leaves on Windows.
fn remove_dir(dir: &Path) -> std::io::Result<()> {
    fn writable(dir: &Path) {
        if let Ok(entries) = std::fs::read_dir(dir) {
            for e in entries.flatten() {
                let path = e.path();
                if let Ok(meta) = std::fs::symlink_metadata(&path) {
                    let mut perms = meta.permissions();
                    #[allow(clippy::permissions_set_readonly_false)]
                    perms.set_readonly(false);
                    let _ = std::fs::set_permissions(&path, perms);
                    if meta.is_dir() {
                        writable(&path);
                    }
                }
            }
        }
    }
    std::fs::remove_dir_all(dir).or_else(|_| {
        writable(dir);
        std::fs::remove_dir_all(dir)
    })
}

fn git(dir: Option<&Path>, args: &[&str]) -> Result<String, String> {
    let mut cmd = Command::new("git");
    if let Some(d) = dir {
        cmd.arg("-C").arg(d);
    }
    let out = cmd
        .args(args)
        .env("GIT_ALLOW_PROTOCOL", "file:https:ssh:git")
        .env("GIT_TERMINAL_PROMPT", "0")
        .stdin(Stdio::null())
        .output()
        .map_err(|e| format!("cannot run git: {e} (is git installed?)"))?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
    } else {
        Err(format!(
            "git {} failed: {}",
            args.first().copied().unwrap_or(""),
            String::from_utf8_lossy(&out.stderr).trim()
        ))
    }
}

fn commit_of(dir: &Path, rev: &str) -> Option<String> {
    git(
        Some(dir),
        &[
            "rev-parse",
            "--verify",
            "--quiet",
            &format!("{rev}^{{commit}}"),
        ],
    )
    .ok()
}

/// Makes `.qlang/packages/<name>` a checkout of `url`, and returns the commit it wants:
/// `locked` if given, else what `spec` points to now.
fn fetch(dest: &Path, url: &str, spec: &GitRef, locked: Option<&str>) -> Result<String, String> {
    let same_origin = dest.join(".git").is_dir()
        && git(Some(dest), &["remote", "get-url", "origin"])
            .ok()
            .as_deref()
            == Some(url);
    if dest.exists() && !same_origin {
        remove_dir(dest).map_err(|e| format!("cannot replace {}: {e}", dest.display()))?;
    }
    if let Some(c) = locked {
        // already there at that commit: nothing to do
        if same_origin && git(Some(dest), &["rev-parse", "HEAD"]).ok().as_deref() == Some(c) {
            return Ok(c.to_string());
        }
    }
    if !dest.exists() {
        std::fs::create_dir_all(dest.parent().expect("a package has a parent"))
            .map_err(|e| e.to_string())?;
        git(
            None,
            &[
                "clone",
                "--quiet",
                "--no-checkout",
                "--",
                url,
                &dest.to_string_lossy(),
            ],
        )?;
    } else {
        git(
            Some(dest),
            &["fetch", "--quiet", "--tags", "--force", "origin"],
        )?;
    }
    let commit = match locked {
        Some(c) => commit_of(dest, c).ok_or_else(|| {
            format!("{url} no longer has the locked commit {c} (run `qlang update`)")
        })?,
        None => {
            let rev = match spec {
                GitRef::Default => "origin/HEAD".to_string(),
                GitRef::Tag(t) => format!("refs/tags/{t}"),
                GitRef::Rev(r) => r.clone(),
                GitRef::Branch(b) => format!("refs/remotes/origin/{b}"),
            };
            commit_of(dest, &rev).ok_or_else(|| format!("{url} has no {} ({rev})", spec.label()))?
        }
    };
    git(
        Some(dest),
        &["checkout", "--quiet", "--detach", "--force", &commit],
    )?;
    Ok(commit)
}

/// What to refresh: everything, or the named packages.
pub enum Refresh {
    Nothing,
    All,
    Some(Vec<String>),
}

/// Installs every git package the project at `project` depends on, directly or through
/// other packages, and rewrites the lock file.
pub fn install(project: &Path, refresh: &Refresh) -> Result<(), String> {
    let manifest = manifest_of(project)?;
    let lock = read_lock(project)?;
    let mut new_lock: BTreeMap<String, Locked> = BTreeMap::new();
    let mut seen: HashMap<String, Source> = HashMap::new();
    let mut queue: Vec<(String, Source, String, bool)> = Vec::new();
    if let Some(m) = &manifest {
        for (n, s) in parse_dependencies(m, project, "this project")?
            .into_iter()
            .rev()
        {
            queue.push((n, s, "this project".to_string(), true));
        }
    }
    while let Some((name, source, owner, local_ok)) = queue.pop() {
        if let Some(known) = seen.get(&name) {
            if *known == source {
                continue;
            }
            return Err(format!(
                "{owner}: dependency `{name}` asks for a different source than elsewhere (one version of each package per project)"
            ));
        }
        seen.insert(name.clone(), source.clone());
        let (dir, nested_local) = match &source {
            Source::Path(dir) => {
                if !local_ok {
                    return Err(format!(
                        "{owner}: dependency `{name}`: a package fetched from git cannot depend on a local path"
                    ));
                }
                (
                    dir.canonicalize().map_err(|_| {
                        format!(
                            "{owner}: dependency `{name}`: the directory {} does not exist",
                            dir.display()
                        )
                    })?,
                    true,
                )
            }
            Source::Git { url, spec } => {
                let refreshed = match refresh {
                    Refresh::Nothing => false,
                    Refresh::All => true,
                    Refresh::Some(names) => names.contains(&name),
                };
                let locked = lock
                    .get(&name)
                    .filter(|l| !refreshed && l.git == *url && l.spec == spec.label())
                    .map(|l| l.commit.as_str());
                let dest = packages_dir(project).join(&name);
                let commit = fetch(&dest, url, spec, locked)?;
                println!(
                    "{name} {} -> {}",
                    spec.label(),
                    &commit[..commit.len().min(10)]
                );
                new_lock.insert(
                    name.clone(),
                    Locked {
                        git: url.clone(),
                        spec: spec.label(),
                        commit,
                    },
                );
                (dest, false)
            }
        };
        let owner = format!("package `{name}`");
        if let Some(m) = manifest_of(&dir)? {
            for (n, s) in parse_dependencies(&m, &dir, &owner)?.into_iter().rev() {
                queue.push((n, s, owner.clone(), nested_local));
            }
        }
    }
    // packages nobody depends on any more
    let keep: HashSet<&String> = new_lock.keys().collect();
    if let Ok(entries) = std::fs::read_dir(packages_dir(project)) {
        for e in entries.flatten() {
            if !keep.contains(&e.file_name().to_string_lossy().into_owned()) {
                let _ = remove_dir(&e.path());
            }
        }
    }
    write_lock(project, &new_lock)
}

/// The `qlang.toml` to edit: the one governing the current directory, or a new one here.
fn manifest_path(cwd: &Path) -> PathBuf {
    crate::providers::find_config(cwd).unwrap_or_else(|| cwd.join("qlang.toml"))
}

fn edit(file: &Path) -> Result<toml_edit::DocumentMut, String> {
    let text = if file.is_file() {
        std::fs::read_to_string(file).map_err(|e| format!("cannot read {}: {e}", file.display()))?
    } else {
        String::new()
    };
    text.parse().map_err(|e| format!("{}: {e}", file.display()))
}

/// `qlang add name --git URL [--tag T | --rev R | --branch B]` or `--path DIR`.
pub fn add(cwd: &Path, name: &str, options: &[(&str, &str)]) -> Result<PathBuf, String> {
    if !qlang_core::span::valid_package_name(name) {
        return Err(format!(
            "`{name}` is not a valid package name (letters, digits, `_` and `-`)"
        ));
    }
    let file = manifest_path(cwd);
    let mut doc = edit(&file)?;
    let mut dep = toml_edit::InlineTable::new();
    for (key, value) in options {
        if !["git", "tag", "rev", "branch", "path"].contains(key) {
            return Err(format!("unknown option --{key}"));
        }
        dep.insert(*key, (*value).into());
    }
    if !(dep.contains_key("git") ^ dep.contains_key("path")) {
        return Err("give the package a source: --git URL or --path DIR".to_string());
    }
    let deps = doc
        .entry("dependencies")
        .or_insert(toml_edit::table())
        .as_table_mut()
        .ok_or("`dependencies` in qlang.toml must be a table")?;
    deps.insert(name, toml_edit::value(dep));
    std::fs::write(&file, doc.to_string())
        .map_err(|e| format!("cannot write {}: {e}", file.display()))?;
    Ok(file.parent().expect("a file has a parent").to_path_buf())
}

/// `qlang remove name`.
pub fn remove(cwd: &Path, name: &str) -> Result<PathBuf, String> {
    let file = manifest_path(cwd);
    let mut doc = edit(&file)?;
    let removed = doc
        .get_mut("dependencies")
        .and_then(|d| d.as_table_mut())
        .and_then(|t| t.remove(name));
    if removed.is_none() {
        return Err(format!(
            "`{name}` is not a dependency in {}",
            file.display()
        ));
    }
    std::fs::write(&file, doc.to_string())
        .map_err(|e| format!("cannot write {}: {e}", file.display()))?;
    Ok(file.parent().expect("a file has a parent").to_path_buf())
}
