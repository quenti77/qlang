//! The formats of `qlang.toml` and `qlang.lock`: what the 1.0 promises about the files a project keeps.
//! `docs/stability.md` lists them next to the commands; these tests are their executable definition.
//! The ones that need git are skipped when it is not installed.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn have_git() -> bool {
    Command::new("git")
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success())
}

fn git(dir: &Path, args: &[&str]) -> String {
    let o = Command::new("git")
        .args(["-c", "user.name=t", "-c", "user.email=t@t"])
        .args(["-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false"])
        .args(["-c", "init.defaultBranch=main"])
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap();
    assert!(
        o.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&o.stderr)
    );
    String::from_utf8_lossy(&o.stdout).trim().to_string()
}

struct Dir(PathBuf);

impl Dir {
    fn new(name: &str) -> Dir {
        let p = std::env::temp_dir().join(format!("qlang-manifest-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&p);
        fs::create_dir_all(p.join("app")).unwrap();
        Dir(p)
    }

    fn write(&self, rel: &str, text: &str) {
        let f = self.0.join(rel);
        fs::create_dir_all(f.parent().unwrap()).unwrap();
        fs::write(f, text).unwrap();
    }

    fn read(&self, rel: &str) -> String {
        fs::read_to_string(self.0.join(rel)).unwrap_or_default()
    }

    /// A repository with `lib.q` printing `version`, tagged `tag`; returns its path and its commit.
    fn repo(&self, name: &str, version: &str, tag: &str) -> (String, String) {
        let dir = self.0.join("repos").join(name);
        fs::create_dir_all(&dir).unwrap();
        git(&dir, &["init", "--quiet"]);
        self.lib(name, version);
        git(&dir, &["add", "."]);
        git(&dir, &["commit", "--quiet", "-m", "first"]);
        git(&dir, &["tag", tag]);
        let commit = git(&dir, &["rev-parse", "HEAD"]);
        (dir.to_string_lossy().replace('\\', "/"), commit)
    }

    fn lib(&self, name: &str, version: &str) {
        fs::write(
            self.0.join("repos").join(name).join("lib.q"),
            format!("fun version() -> string\n  \"{version}\"\nend\nexport version\n"),
        )
        .unwrap();
    }

    fn qlang(&self, args: &[&str]) -> (String, String, bool) {
        let o = Command::new(env!("CARGO_BIN_EXE_qlang"))
            .args(args)
            .current_dir(self.0.join("app"))
            .output()
            .unwrap();
        (
            String::from_utf8_lossy(&o.stdout).into_owned(),
            String::from_utf8_lossy(&o.stderr).into_owned(),
            o.status.success(),
        )
    }
}

impl Drop for Dir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

const APP: &str = "import \"@mail\" as m\nprint(m.version())\n";

#[test]
fn the_lock_is_written_in_this_exact_shape() {
    if !have_git() {
        return;
    }
    let d = Dir::new("shape");
    let (url, commit) = d.repo("mail", "v1", "v1.0.0");
    let (text, commit_text) = d.repo("text", "t1", "v0.3.0");
    d.write(
        "app/qlang.toml",
        &format!(
            "[dependencies]\nmail = {{ git = \"{url}\", tag = \"v1.0.0\" }}\ntext = {{ git = \"{text}\", rev = \"{commit_text}\" }}\n"
        ),
    );
    d.write("app/main.q", APP);
    let (_, err, ok) = d.qlang(&["install"]);
    assert!(ok, "{err}");
    // one `[[package]]` per dependency, by name; `ref` says how it was chosen: `tag:`, `rev:` or `branch:`
    let expected = format!(
        "# generated by `qlang install`; commit it, do not edit it\n\
         \n[[package]]\nname = \"mail\"\ngit = \"{url}\"\nref = \"tag:v1.0.0\"\ncommit = \"{commit}\"\n\
         \n[[package]]\nname = \"text\"\ngit = \"{text}\"\nref = \"rev:{commit_text}\"\ncommit = \"{commit_text}\"\n"
    );
    assert_eq!(d.read("app/qlang.lock"), expected);
    // installing again changes nothing
    assert!(d.qlang(&["install"]).2);
    assert_eq!(d.read("app/qlang.lock"), expected);
}

#[test]
fn a_lock_in_that_shape_is_obeyed_even_if_the_repository_moved_on() {
    if !have_git() {
        return;
    }
    let d = Dir::new("obeyed");
    let (url, first) = d.repo("mail", "one", "v1.0.0");
    let dir = d.0.join("repos/mail");
    d.lib("mail", "two");
    git(&dir, &["add", "."]);
    git(&dir, &["commit", "--quiet", "-m", "next"]);
    git(&dir, &["tag", "-f", "v1.0.0"]);
    d.write(
        "app/qlang.toml",
        &format!("[dependencies]\nmail = {{ git = \"{url}\", tag = \"v1.0.0\" }}\n"),
    );
    d.write("app/main.q", APP);
    d.write(
        "app/qlang.lock",
        &format!(
            "# generated by `qlang install`; commit it, do not edit it\n\n[[package]]\nname = \"mail\"\ngit = \"{url}\"\nref = \"tag:v1.0.0\"\ncommit = \"{first}\"\n"
        ),
    );
    let (_, err, ok) = d.qlang(&["install"]);
    assert!(ok, "{err}");
    assert_eq!(d.qlang(&["run", "main.q"]).0, "one\n");
}

#[test]
fn every_documented_key_of_the_manifest_is_accepted() {
    let d = Dir::new("keys");
    d.write(
        "mail/lib.q",
        "fun version() -> string\n  \"local\"\nend\nexport version\n",
    );
    d.write(
        "app/qlang.toml",
        "# a comment\n\
         [package]\nname = \"app\"\nversion = \"1.2.3\"\nentry = \"main.q\"\nmain = \"lib.q\"\nqlang = \"0.1\"\n\
         \n[dependencies]\nmail = { path = \"../mail\" }\n\
         \n[stability]\nstable = [\"main.q\"]\nprovisional = [\"web/*.q\"]\nexperimental = [\"**/*.q\"]\n",
    );
    d.write("app/main.q", APP);
    // `entry` is what `run` and `check` take without a file
    let (out, err, ok) = d.qlang(&["run"]);
    assert!(ok, "{err}");
    assert_eq!(out, "local\n");
    assert!(d.qlang(&["check"]).2);
    // a package's `main` is the file `import "@name"` loads
    d.write(
        "mail/qlang.toml",
        "[package]\nname = \"mail\"\nmain = \"src/mail.q\"\n",
    );
    d.write(
        "mail/src/mail.q",
        "fun version() -> string\n  \"from main\"\nend\nexport version\n",
    );
    assert_eq!(d.qlang(&["run"]).0, "from main\n");
}

#[test]
fn the_manifest_must_be_toml_and_a_requirement_newer_than_qlang_stops_the_project() {
    let d = Dir::new("bad");
    d.write("app/main.q", "print(1)\n");
    d.write("app/qlang.toml", "[package\nname = \n");
    assert!(!d.qlang(&["run", "main.q"]).2);
    d.write(
        "app/qlang.toml",
        "[package]\nname = \"app\"\nqlang = \"99.0\"\n",
    );
    let (_, err, ok) = d.qlang(&["run", "main.q"]);
    assert!(!ok);
    assert!(err.contains("this project needs qlang 99.0"), "{err}");
}
